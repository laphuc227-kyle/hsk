/**
 * Normalizes user radical string or extracts canonical radical info.
 * e.g. "氵 (Thủy)", "氵", "水", "Thủy", "子 (Tử)" -> matched RadicalInfo
 */
export function findRadicalInfo(keyword: string): RadicalInfo | null {
  if (!keyword) return null;
  const raw = keyword.trim().toLowerCase();

  // 1. Direct match with hanzi or variants
  for (const r of KANGXI_RADICALS_DATABASE) {
    if (r.hanzi === keyword.trim()) return r;
    if (r.variants.includes(keyword.trim())) return r;
  }

  // 2. Match with Han Viet name or keyword within string (e.g. "氵 (Thủy)" -> matches Thủy)
  for (const r of KANGXI_RADICALS_DATABASE) {
    const hanVietLower = r.hanViet.toLowerCase();
    if (raw === hanVietLower) return r;
    if (raw.includes(hanVietLower)) return r;
    if (raw.includes(r.hanzi.toLowerCase())) return r;
    for (const v of r.variants) {
      if (raw.includes(v.toLowerCase())) return r;
    }
  }

  // 3. Match within meaning or description
  for (const r of KANGXI_RADICALS_DATABASE) {
    if (raw.includes(r.meaning.toLowerCase())) return r;
  }

  return null;
}

/**
 * Helper to get a clean display title for a radical
 * e.g. "氵 (Bộ Thủy - Nước)"
 */
export function formatRadicalTitle(radicalStr: string): string {
  const info = findRadicalInfo(radicalStr);
  if (!info) return radicalStr;
  const mainSymbol = info.variants.length > 0 ? `${info.variants[0]} (${info.hanzi})` : info.hanzi;
  return `${mainSymbol} ${info.hanViet} · ${info.meaning.split(',')[0]}`;
}
