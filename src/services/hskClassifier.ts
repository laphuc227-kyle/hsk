/**
 * Classifies a Chinese character/word into its HSK level ID
 */
export function classifyWordHSK(word: string): 'hsk1' | 'hsk2' | 'hsk3' {
  if (HSK1_SET.has(word)) return 'hsk1';
  if (HSK2_SET.has(word)) return 'hsk2';
  if (HSK3_SET.has(word)) return 'hsk3';

  // If word is multi-character compound, check if all or any characters are in HSK1
  const chars = Array.from(word);
  const allInHsk1 = chars.every((c) => HSK1_SET.has(c));
  if (allInHsk1) return 'hsk1';

  const anyInHsk1 = chars.some((c) => HSK1_SET.has(c));
  if (anyInHsk1) return 'hsk1';

  const anyInHsk2 = chars.some((c) => HSK2_SET.has(c));
  if (anyInHsk2) return 'hsk2';

  return 'hsk1'; // default fallback
}

/**
 * Auto-categorizes a list of characters into their matching HSK listIds
 */
export function autoCategorizeCharacters(characters: Character[]): Character[] {
  return characters.map((char) => {
    const hskLevel = classifyWordHSK(char.hanzi);
    // Ensure listIds contains the classified HSK level
    const updatedLists = Array.from(new Set([...char.listIds, hskLevel]));
    return {
      ...char,
      listIds: updatedLists,
    };
  });
}
